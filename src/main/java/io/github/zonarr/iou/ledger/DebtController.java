package io.github.zonarr.iou.ledger;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import io.github.zonarr.iou.auth.Actor;
import io.github.zonarr.iou.ledger.LedgerDtos.DebtRequest;
import io.github.zonarr.iou.ledger.LedgerDtos.DebtView;
import jakarta.validation.Valid;
import java.util.List;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

@Tag(name = "Debts", description = "Simple IOUs and the debts generated by expenses")
@RestController
@RequestMapping("/api")
public class DebtController {

    private final DebtService debts;

    public DebtController(DebtService debts) {
        this.debts = debts;
    }

    /** Records a simple IOU between two members of a group. */
    @Operation(summary = "Record a simple IOU in a group")
    @PostMapping("/groups/{groupId}/debts")
    @ResponseStatus(HttpStatus.CREATED)
    public DebtView createInGroup(Actor actor, @PathVariable long groupId, @Valid @RequestBody DebtRequest request) {
        return debts.create(actor.id(), groupId, request);
    }

    /** All debts in the group: standalone IOUs and the ones generated from expenses. */
    @Operation(summary = "All debts in a group")
    @GetMapping("/groups/{groupId}/debts")
    public List<DebtView> listInGroup(Actor actor, @PathVariable long groupId) {
        return debts.listInGroup(actor.id(), groupId);
    }

    /** Records a one-on-one IOU (no group). You must be the debtor or the creditor. */
    @Operation(summary = "Record a one-on-one IOU (no group)")
    @PostMapping("/debts")
    @ResponseStatus(HttpStatus.CREATED)
    public DebtView createDirect(Actor actor, @Valid @RequestBody DebtRequest request) {
        return debts.create(actor.id(), null, request);
    }

    /** My one-on-one debts (no group). */
    @Operation(summary = "My one-on-one debts")
    @GetMapping("/debts")
    public List<DebtView> listDirect(Actor actor) {
        return debts.listDirect(actor.id());
    }

    @Operation(summary = "One debt")
    @GetMapping("/debts/{id}")
    public DebtView get(Actor actor, @PathVariable long id) {
        return debts.get(actor.id(), id);
    }

    /** Changes a standalone IOU. Changing who or how much sends it back to pending. */
    @Operation(summary = "Change a standalone IOU (changing who or how much sends it back to pending)")
    @PutMapping("/debts/{id}")
    public DebtView update(Actor actor, @PathVariable long id, @Valid @RequestBody DebtRequest request) {
        return debts.update(actor.id(), id, request);
    }

    @Operation(summary = "Delete a standalone IOU")
    @DeleteMapping("/debts/{id}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    public void delete(Actor actor, @PathVariable long id) {
        debts.delete(actor.id(), id);
    }

    /** Debtor confirms a pending debt. */
    @Operation(summary = "Debtor confirms a pending debt")
    @PostMapping("/debts/{id}/accept")
    public DebtView accept(Actor actor, @PathVariable long id) {
        return debts.accept(actor.id(), id);
    }

    /** Debtor rejects a pending debt. */
    @Operation(summary = "Debtor rejects a pending debt")
    @PostMapping("/debts/{id}/reject")
    public DebtView reject(Actor actor, @PathVariable long id) {
        return debts.reject(actor.id(), id);
    }
}
