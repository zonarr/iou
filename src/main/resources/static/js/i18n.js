export const dictionaries = { en, th };

const LANG_KEY = 'iou.lang';
function initialLanguage() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'th') return saved;
  } catch { /* ignore */ }
  return (navigator.language || 'en').toLowerCase().startsWith('th') ? 'th' : 'en';
}

export const language = createStore({ lang: initialLanguage() });
document.documentElement.lang = language.get().lang;

export function setLanguage(lang) {
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
  language.set({ lang });
}

export function t(key, vars) {
  const dict = dictionaries[language.get().lang] || en;
  let text = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value);
  }
  return text;
}

/** Text for an error from the API: a translation of its code if we have one, else its own message. */
export function errorText(error) {
  if (!error) return '';
  const key = `err.${error.code}`;
  const dict = dictionaries[language.get().lang] || en;
  if (dict[key] || en[key]) return t(key);
  return error.message || t('err.generic');
}

/** "17 Dec" / "17 ธ.ค." */
export function formatDay(isoDate) {
  const date = new Date(isoDate.length <= 10 ? `${isoDate}T00:00:00` : isoDate);
  return date.toLocaleDateString(language.get().lang === 'th' ? 'th-TH' : 'en-GB',
    { day: 'numeric', month: 'short', weekday: 'short' });
}

export function formatDateTime(iso) {
  return new Date(iso).toLocaleString(language.get().lang === 'th' ? 'th-TH' : 'en-GB',
    { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
}
